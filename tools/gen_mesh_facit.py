# Generates test/mesh_smoothing_facit.inc: meshes and the extents AutoCAD computed for them when
# smoothed (plan phase 4, B49). Each case was written as a 2010 DXF (one MESH in AutoCAD 2017's
# new drawing), read by AutoCAD 2027's own engine (DWG TrueView's accoreconsole), saved with
# ZOOM E and -WBLOCK * as DWG, and the DWG made DXF by ODA File Converter, which keeps the
# header's $EXTMIN/$EXTMAX as AutoCAD computed them (with AutoCAD's noise of about 1e-8).
# Run: py -I tools/gen_mesh_facit.py BATTERY_DIR... > test/mesh_smoothing_facit.inc
# (each BATTERY_DIR has cases.json and wbdxf/<case>.dxf)
import json
import os
import sys


def extents(path):
    t = open(path, 'rb').read().decode('latin-1').replace('\r\n', '\n').split('\n')
    v = {}
    for i in range(len(t)):
        if t[i].strip() in ('$EXTMIN', '$EXTMAX'):
            v[t[i].strip()] = [float(t[i + 2]), float(t[i + 4]), float(t[i + 6])]
    return v['$EXTMIN'] + v['$EXTMAX']


def num(x):
    return repr(float(x))


def main():
    out = ['// generated by tools/gen_mesh_facit.py: AutoCAD 2027\'s extents of smoothed meshes (B49)']
    for d in sys.argv[1:]:
        for c in json.load(open(os.path.join(d, 'cases.json'))):
            p = os.path.join(d, 'wbdxf', c['name'] + '.dxf')
            if not os.path.exists(p):
                continue
            e = extents(p)
            verts = ', '.join('{%s, %s, %s}' % tuple(num(x) for x in v) for v in c['v'])
            faces = ', '.join('{' + ', '.join(str(i) for i in f) + '}' for f in c['f'])
            creases = ', '.join('{%s, %s, %s}' % (k.split('-')[0], k.split('-')[1], num(v))
                                for k, v in c.get('creases', {}).items())
            out.append('{"%s", %d, %d, {%s}, {%s}, {%s}, {%s}},' % (
                c['name'], c['level'], c.get('blend', 0), verts, faces, creases, ', '.join(num(x) for x in e)))
    sys.stdout.write('\n'.join(out) + '\n')


main()
