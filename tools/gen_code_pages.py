# Generates src/code_pages.cpp: the code pages AutoCAD names in $DWGCODEPAGE, as tables of
# Unicode code points — Windows' own mappings (MultiByteToWideChar), which AutoCAD uses, so
# the Windows extensions (CP936 0x80 = euro, the private-use areas of 936/950 …) are in.
# A page Windows does not have (ISO8859-10) comes from the Unicode consortium's mapping
# (Python's codec). Run on Windows: py -I tools/gen_code_pages.py src/code_pages.cpp
import ctypes

_kernel32 = ctypes.windll.kernel32
MB_ERR_INVALID_CHARS = 8

def windows_decode(code_page, data):
    # The code points Windows gives for the bytes, or None when they are not a character
    buf = ctypes.create_unicode_buffer(8)
    n = _kernel32.MultiByteToWideChar(code_page, MB_ERR_INVALID_CHARS, data, len(data), buf, 8)
    if n <= 0:
        return None
    return buf[:n]

# Single-byte: AutoCAD's name(s), the Windows code page number, Python's codec
SINGLE = [
    (["ANSI_1250"], 1250, "cp1250"), (["ANSI_1251"], 1251, "cp1251"), (["ANSI_1252"], 1252, "cp1252"),
    (["ANSI_1253"], 1253, "cp1253"), (["ANSI_1254"], 1254, "cp1254"), (["ANSI_1255"], 1255, "cp1255"),
    (["ANSI_1256"], 1256, "cp1256"), (["ANSI_1257"], 1257, "cp1257"), (["ANSI_1258"], 1258, "cp1258"),
    (["ANSI_874"], 874, "cp874"),
    (["DOS437", "CP437"], 437, "cp437"), (["DOS850", "CP850"], 850, "cp850"),
    (["DOS852", "CP852"], 852, "cp852"), (["DOS855", "CP855"], 855, "cp855"),
    (["DOS857", "CP857"], 857, "cp857"), (["DOS860", "CP860"], 860, "cp860"),
    (["DOS861", "CP861"], 861, "cp861"), (["DOS863", "CP863"], 863, "cp863"),
    (["DOS864", "CP864"], 864, "cp864"), (["DOS865", "CP865"], 865, "cp865"),
    (["DOS866", "CP866"], 866, "cp866"), (["DOS869", "CP869"], 869, "cp869"),
    (["MACINTOSH"], 10000, "mac_roman"),
] + [(["ISO8859-%d" % n], 28590 + n, "iso8859_%d" % n) for n in range(1, 11)]

# Double-byte: AutoCAD's names, the number, the codec, the \M+ digit AutoCAD uses for it
DOUBLE = [
    (["ANSI_932", "DOS932", "CP932"], 932, "cp932", 1),
    (["ANSI_950", "BIG5"], 950, "cp950", 2),
    (["ANSI_949", "KSC5601"], 949, "cp949", 3),
    (["ANSI_1361", "JOHAB"], 1361, "johab", 4),
    (["ANSI_936", "GB2312"], 936, "gbk", 5),
]

out = []
w = out.append
w("#include \"text_encoding.hpp\"")
w("#include <algorithm>")
w("#include <cstring>")
w("")
w("// Generated by tools/gen_code_pages.py — do not edit. The code pages AutoCAD names in")
w("// $DWGCODEPAGE as Unicode code points: single-byte ones by their upper half (bytes")
w("// 0x80-0xFF; a byte the code page leaves undefined is the code point with its number, as")
w("// Windows does), double-byte ones as sorted pairs (byte or byte pair → code point).")
w("")
w("namespace hdxf {")
w("namespace internal {")
w("")
w("namespace {")
w("")
for names, num, codec in SINGLE:
    vals = []
    windows = _kernel32.IsValidCodePage(num) != 0      # Windows has no ISO8859-10 (28600)
    for b in range(0x80, 0x100):
        if windows:
            s = windows_decode(num, bytes([b]))
        else:
            try:
                s = bytes([b]).decode(codec)            # the Unicode consortium's mapping
            except UnicodeDecodeError:
                s = None
        vals.append(ord(s) if s is not None and len(s) == 1 else b)
    w("const char16_t cp%d[128] = {" % num)
    for i in range(0, 128, 8):
        w("    " + ", ".join("0x%04X" % v for v in vals[i:i + 8]) + ",")
    w("};")
    w("")
for names, num, codec, digit in DOUBLE:
    pairs = []
    for b in range(0x80, 0x100):
        s = windows_decode(num, bytes([b]))
        if s is not None and len(s) == 1:
            pairs.append((b, ord(s)))
    single = {code for code, cp in pairs}
    for lead in range(0x81, 0x100):
        if lead in single:
            continue
        for trail in range(0x30, 0x100):
            s = windows_decode(num, bytes([lead, trail]))
            if s is not None and len(s) == 1 and ord(s) != 0xFFFD:
                pairs.append((lead << 8 | trail, ord(s)))
    pairs.sort()
    w("const DoubleBytePair cp%d_pairs[] = {" % num)
    line = []
    for code, cp in pairs:
        line.append("{0x%04X, 0x%04X}" % (code, cp))
        if len(line) == 6:
            w("    " + ", ".join(line) + ",")
            line = []
    if line: w("    " + ", ".join(line) + ",")
    w("};")
    w("")
w("} // namespace")
w("")
w("const char16_t* code_page_table(int code_page) {")
w("    switch (code_page) {")
for names, num, codec in SINGLE:
    w("        case %d: return cp%d;" % (num, num))
w("        default: return nullptr;")
w("    }")
w("}")
w("")
w("const DoubleBytePage* double_byte_page(int code_page) {")
for names, num, codec, digit in DOUBLE:
    w("    static const DoubleBytePage p%d = {%d, %d, cp%d_pairs, sizeof(cp%d_pairs) / sizeof(cp%d_pairs[0])};" % (num, num, digit, num, num, num))
w("    switch (code_page) {")
for names, num, codec, digit in DOUBLE:
    w("        case %d: return &p%d;" % (num, num))
w("        default: return nullptr;")
w("    }")
w("}")
w("")
w("int code_page_for_mif(int digit) {")
w("    switch (digit) {")
for names, num, codec, digit in DOUBLE:
    w("        case %d: return %d;" % (digit, num))
w("        default: return 0;")
w("    }")
w("}")
w("")
w("int code_page_number(const std::string& upper_name) {")
w("    struct Name { const char* name; int number; };")
w("    static const Name names[] = {")
for names, num, *_ in SINGLE + [(d[0], d[1]) for d in DOUBLE]:
    for n in names:
        w("        {\"%s\", %d}," % (n, num))
w("        {\"ASCII\", 20127},")
w("    };")
w("    for (const auto& n : names) {")
w("        if (upper_name == n.name) return n.number;")
w("    }")
w("    return 0;")
w("}")
w("")
w("} // namespace internal")
w("} // namespace hdxf")
import sys
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
