# Generates test/acis_sab_facit.inc: SAT bodies and the SAB 21800 AutoCAD makes of them (plan phase
# 5, steps 5.6 and 5.7, B63/B66) — the facit of the SAT → SAB encoder (src/acis_sab.cpp) for the
# spline geometry and the attributes (5.6) and the versions before 21200 (5.7: ACadSharp's 2000 and
# 2004 bodies, LibreDWG's Surface_2004 and test_acis.cpp's 7.0 bodies against AutoCAD's chain of an
# HDxf 2010 drawing of them, ezdxf's 3dsolids against ODA's ACAD2013 DXF of the file itself). Only
# bodies of files in test/data/manifest.cmake (and of the tests):
#   --chain LABEL SAT.dxf SAB.dxf  the SAT bodies of SAT.dxf (ODA File Converter's ACAD2010 or ACAD2007
#       DXF of the DWG AutoCAD's chain made: DXFIN, -WBLOCK *) and, in the same order, the SAB of the
#       same bodies in SAB.dxf (AutoCAD's chain of that SAT, or ODA's ACAD2013 DXF of the same DWG)
#   --own LABEL FILE SAT.dxf  the SAT bodies of SAT.dxf (ODA's ACAD2010 DXF of the manifest's FILE, a
#       2013 file from AutoCAD); the facit is FILE's own SAB of the same handle, read by the test
# Run: py -I tools/gen_sab_facit.py SPEC... > test/acis_sab_facit.inc
import sys


def groups(path):
    t = open(path, 'rb').read().decode('latin-1').replace('\r\n', '\n').split('\n')
    return [(int(t[i]), t[i + 1]) for i in range(0, len(t) - 1, 2)]


def caret(v):
    out = []
    i = 0
    while i < len(v):
        if v[i] == '^' and i + 1 < len(v):
            n = v[i + 1]
            out.append('^' if n == ' ' else chr(ord(n) - 64) if 64 <= ord(n) < 96 else '^' + n)
            i += 2
            continue
        out.append(v[i])
        i += 1
    return ''.join(out)


def decipher(line):
    return ''.join(' ' if c == ' ' else chr(159 - ord(c)) if 32 < ord(c) < 159 else c for c in line)


def sat_bodies(path):
    # (handle, SAT text) of every AcDbModelerGeometry with 1/3 lines, in file order; a line is its
    # 3s and the 1 that ends it (AutoCAD's and ODA's form)
    g = groups(path)
    out = []
    handle = None
    i = 0
    while i < len(g):
        c, v = g[i]
        if c == 0:
            handle = None
        elif c == 5:
            handle = v.strip()
        elif c == 100 and v.strip() == 'AcDbModelerGeometry':
            lines, pending = [], ''
            j = i + 1
            while j < len(g) and g[j][0] not in (0, 100):
                if g[j][0] == 1:
                    lines.append(pending + caret(g[j][1]))
                    pending = ''
                elif g[j][0] == 3:
                    pending += caret(g[j][1])
                j += 1
            if lines:
                out.append((handle, ''.join(decipher(l) + '\n' for l in lines)))
            i = j
            continue
        i += 1
    return out


def sab_bodies(path):
    # (handle, hex) of the ASM_Data records of the ACDSDATA section, in file order
    g = groups(path)
    out = []
    i = 0
    while i < len(g):
        if g[i] == (0, 'ACDSRECORD'):
            j = i + 1
            asm, data, handle = False, [], None
            while j < len(g) and g[j][0] != 0:
                if g[j][0] == 2 and g[j][1].strip() == 'ASM_Data':
                    asm = True
                elif g[j][0] == 320:
                    handle = g[j][1].strip()
                elif g[j][0] == 310 and asm:
                    data.append(g[j][1].strip())
                j += 1
            if data:
                out.append((handle, ''.join(data)))
            i = j
            continue
        i += 1
    return out


def literal_hex(h):
    return '\n'.join('     "%s"' % h[k:k + 120] for k in range(0, len(h), 120))


def entry(label, file, handle, sat, sab):
    if ')SAT"' in sat:
        raise SystemExit('a SAT the raw string cannot hold: ' + label)
    return '{"%s", %s, "%s",\n R"SAT(%s)SAT",\n%s},' % (
        label, 'nullptr' if file is None else '"%s"' % file, handle or '', sat,
        literal_hex(sab) if sab else '     ""')


def main():
    out = ['// generated by tools/gen_sab_facit.py: SAT bodies and AutoCAD\'s SAB 21800 of them (plan 5.6)',
           '// {label, the manifest file whose own SAB is the facit (nullptr: the SAB here), its handle,',
           '//  the SAT, the SAB (hex)}']
    a = sys.argv[1:]
    k = 0
    while k < len(a):
        if a[k] == '--chain':
            label, sat_path, sab_path = a[k + 1:k + 4]
            sats, sabs = sat_bodies(sat_path), sab_bodies(sab_path)
            if len(sats) != len(sabs):
                raise SystemExit('%s: %d SAT bodies, %d SAB' % (label, len(sats), len(sabs)))
            # By handle when the SAB file has the SAT file's (ODA's two DXFs of one DWG), else in
            # order (the chain of an HDxf drawing: the entities' order, the records' the same)
            by_handle = dict(sabs)
            same = all(h in by_handle for h, _ in sats)
            for n, (h, sat) in enumerate(sats):
                sab = by_handle[h] if same else sabs[n][1]
                out.append(entry('%s %d' % (label, n + 1), None, None, sat, sab))
            k += 4
        elif a[k] == '--own':
            label, file, sat_path = a[k + 1:k + 4]
            for h, sat in sat_bodies(sat_path):
                out.append(entry('%s %s' % (label, h), file, h, sat, None))
            k += 4
        else:
            raise SystemExit('unknown argument ' + a[k])
    sys.stdout.write('\n'.join(out) + '\n')


main()
