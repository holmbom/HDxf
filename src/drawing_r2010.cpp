void match_visual_styles(Drawing& dwg, DxfVersion version, const std::function<std::string()>& new_handle) {
    if (version < DxfVersion::R2007) return;
    size_t n[3] = {0, 0, 0};
    const DataRecord* forms[3] = {visual_styles_2007(n[0]), visual_styles_2010(n[1]), visual_styles_2013(n[2])};
    int to = version >= DxfVersion::R2013 ? 2 : version >= DxfVersion::R2010 ? 1 : 0;
    size_t count = std::min({n[0], n[1], n[2]});
    std::vector<std::string> gone;          // extension dictionaries and XRECORDs 2013 has not
    std::vector<Object> made;
    for (auto& o : dwg.objects()) {
        if (o.type != ObjectType::VisualStyle) continue;
        // The style's round-trip XRECORD, through its extension dictionary (2007, 2010)
        Object* xdict = dwg.find_object(o.xdictionary);
        Object* record = nullptr;
        if (xdict && xdict->type == ObjectType::Dictionary) {
            for (const auto& e : xdict->as_dictionary().entries) {
                if (e.name != "ACAD_XREC_ROUNDTRIP") continue;
                Object* x = dwg.find_object(e.handle);
                if (x && x->type == ObjectType::XRecord) record = x;
            }
        }
        // Which of AutoCAD's styles, in which form; a style changed since is left as it is
        int from = -1;
        size_t index = 0;
        for (int f = 0; f < 3 && from < 0; ++f) {
            bool roundtrip = f < 2;
            if (roundtrip != (record != nullptr)) continue;
            for (size_t i = 0; i < count; ++i) {
                if (visual_style_equal(o.as_visual_style(), standard_typed_styles(f)[i]) && same_xdata(o.xdata, forms[f][i]) &&
                    (!roundtrip || same_roundtrip(record->as_xrecord(), forms[f][i]))) {
                    from = f;
                    index = i;
                    break;
                }
            }
        }
        if (from < 0 || from == to) continue;
        const DataRecord& r = forms[to][index];
        o.data = Boxed<VisualStyleData>(standard_typed_styles(to)[index]);
        o.xdata.clear();
        for (size_t k = 0; k < r.xdata_count; ++k) {
            if (r.xdata[k].code == 1001) o.xdata.push_back({r.xdata[k].value, {}});
            else if (!o.xdata.empty()) o.xdata.back().items.push_back({r.xdata[k].code, r.xdata[k].value});
        }
        if (to == 2) {
            // 2013: no extension dictionary and no XRECORD
            gone.push_back(record->handle);
            gone.push_back(xdict->handle);
            o.xdictionary.clear();
            continue;
        }
        XRecordData x;
        for (size_t k = 0; k < r.roundtrip_count; ++k) x.data.push_back({r.roundtrip[k].code, r.roundtrip[k].value});
        if (record) {
            record->as_xrecord() = std::move(x);
            continue;
        }
        // From 2013: the extension dictionary (no reactors) and its XRECORD (the dictionary as
        // owner and reactor), as ensure_r2007_objects() makes them
        Object dict;
        dict.type = ObjectType::Dictionary;
        dict.handle = new_handle();
        dict.owner = o.handle;
        std::string record_handle = new_handle();
        DictionaryData dd;
        dd.hard_owner = true;
        dd.entries.push_back({"ACAD_XREC_ROUNDTRIP", record_handle, true});
        dict.data = dd;
        Object rec;
        rec.type = ObjectType::XRecord;
        rec.handle = record_handle;
        rec.owner = dict.handle;
        rec.reactors.push_back(dict.handle);
        rec.data = std::move(x);
        o.xdictionary = dict.handle;
        made.push_back(std::move(dict));
        made.push_back(std::move(rec));
    }
    auto& objects = dwg.objects();
    objects.erase(std::remove_if(objects.begin(), objects.end(), [&](const Object& o) {
        return std::find(gone.begin(), gone.end(), o.handle) != gone.end();
    }), objects.end());
    for (auto& o : made) objects.push_back(std::move(o));
}

