bool same_xdata(const std::vector<XdataList>& x, const DataRecord& r) {
    std::vector<DxfGroup> flat;
    for (const auto& list : x) {
        flat.push_back({1001, list.app_name});
        for (const auto& item : list.items) flat.push_back({item.code, item.value});
    }
    if (flat.size() != r.xdata_count) return false;
    for (size_t i = 0; i < flat.size(); ++i) {
        if (flat[i].code != r.xdata[i].code || flat[i].value != r.xdata[i].value) return false;
    }
    return true;
}

bool same_roundtrip(const XRecordData& x, const DataRecord& r) {
    if (x.data.size() != r.roundtrip_count) return false;
    for (size_t i = 0; i < x.data.size(); ++i) {
        if (x.data[i].code != r.roundtrip[i].code || x.data[i].value != r.roundtrip[i].value) return false;
    }
    return true;
}

