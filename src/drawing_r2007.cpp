void Drawing::ensure_r2007_objects() {
    ensure_r2000_structure();
    Object* root = nullptr;
    for (auto& o : objects_) {
        if (o.type == ObjectType::Dictionary && o.owner == "0") { root = &o; break; }
    }
    if (!root) return;
    bool has_materials = false;
    bool has_styles = false;
    for (const auto& entry : root->as_dictionary().entries) {
        has_materials = has_materials || entry.name == "ACAD_MATERIAL";
        has_styles = has_styles || entry.name == "ACAD_VISUALSTYLE";
    }
    if (has_materials && has_styles) return;
    scan_handles();

    // Dictionary entries sorted by name, as AutoCAD writes them; owners before what they own
    auto fill = [&](const std::string& dict_handle, const std::vector<std::pair<std::string, std::string>>& entries) {
        Object* dict = find_object(dict_handle);
        if (!dict) return;
        std::vector<std::pair<std::string, std::string>> sorted = entries;
        std::sort(sorted.begin(), sorted.end());
        for (const auto& [name, handle] : sorted) dict->as_dictionary().entries.push_back({name, handle, false});
    };

    if (!has_materials) {
        std::string dict = named_dictionary("ACAD_MATERIAL");
        std::vector<std::pair<std::string, std::string>> entries;
        std::vector<Object> made;
        for (const DataRecord& r : materials) {
            std::string handle = next_handle();
            entries.push_back({first_value(r, 1), handle});
            made.push_back(object_of(ObjectType::Material, handle, dict, true,
                                     Boxed<MaterialData>(internal::typed_material(r))));
        }
        fill(dict, entries);
        for (auto& o : made) objects_.push_back(std::move(o));
    }
    if (!has_styles) {
        std::string dict = named_dictionary("ACAD_VISUALSTYLE");
        std::vector<std::pair<std::string, std::string>> entries;
        std::vector<Object> styles, xdicts, records;
        // In the form of the version the drawing is made as (B45)
        size_t count = 0;
        const DataRecord* data = version_ >= DxfVersion::R2013 ? internal::visual_styles_2013(count)
                               : version_ >= DxfVersion::R2010 ? internal::visual_styles_2010(count)
                                                               : internal::visual_styles_2007(count);
        // 2013's styles have no extension dictionary or round-trip XRECORD (B59)
        bool roundtrip = version_ < DxfVersion::R2013;
        for (size_t i = 0; i < count; ++i) {
            const DataRecord& r = data[i];
            std::string handle = next_handle();
            entries.push_back({first_value(r, 2), handle});
            Object style = object_of(ObjectType::VisualStyle, handle, dict, true,
                                     Boxed<VisualStyleData>(internal::typed_visual_style(r)));
            style.xdata = xdata_of(r);
            if (!roundtrip) {
                styles.push_back(std::move(style));
                continue;
            }
            std::string xdict = next_handle();
            std::string record = next_handle();
            style.xdictionary = xdict;
            styles.push_back(std::move(style));
            // The extension dictionary has no reactors, its XRECORD has the dictionary
            DictionaryData d;
            d.hard_owner = true;
            d.entries.push_back({"ACAD_XREC_ROUNDTRIP", record, true});
            xdicts.push_back(object_of(ObjectType::Dictionary, xdict, handle, false, d));
            XRecordData x;
            for (size_t k = 0; k < r.roundtrip_count; ++k) x.data.push_back({r.roundtrip[k].code, r.roundtrip[k].value});
            records.push_back(object_of(ObjectType::XRecord, record, xdict, true, x));
        }
        // AutoCAD's order: the styles in their dictionary's (name) order, then their
        // extension dictionaries, then the XRECORDs (2007, 2010; 2013 has neither)
        std::vector<size_t> order(styles.size());
        for (size_t i = 0; i < order.size(); ++i) order[i] = i;
        std::sort(order.begin(), order.end(), [&](size_t a, size_t b) { return entries[a].first < entries[b].first; });
        fill(dict, entries);
        for (size_t i : order) objects_.push_back(styles[i]);
        if (roundtrip) {
            for (size_t i : order) objects_.push_back(xdicts[i]);
            for (size_t i : order) objects_.push_back(records[i]);
        }
    }

    // The header's pointers to them (B32), unless the drawing has its own
    auto point = [&](const char* name, int code, const std::string& handle) {
        const HeaderVar* h = find_header(name);
        if (!h || h->values.empty() || h->values[0].second.empty()) set_header_string(name, code, handle);
    };
    point("$CMATERIAL", 347, internal::material_handle(*this, "ByLayer"));
    point("$INTERFEREOBJVS", 345, internal::visual_style_handle(*this, "Realistic"));
    point("$INTERFEREVPVS", 346, internal::visual_style_handle(*this, "Wireframe"));
}

